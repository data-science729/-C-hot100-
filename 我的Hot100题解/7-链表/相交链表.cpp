/**
 * 题目：相交链表 (LeetCode 160 考研机试/ACM模式版)
 * 来源：力扣hot100考研机试真题
 * 
 * 【题目描述】
 * 给定一个无环的单链式结构和两个头结点。两条链从各自头结点出发后可能在某个结点相交；
 * 一旦相交，后续结点完全相同。
 * 求两条链的第一个公共结点。结点值相同不代表是同一个结点，必须按结点编号判断结点身份。
 * 
 * 【输入格式】
 * 第一行输入三个整数 n, hA, hB，分别表示结点总数和两条链的头结点编号。
 * 结点编号为 0 到 n - 1，头结点编号为 -1 表示对应链为空。
 * 接下来 n 行，第 i 行输入两个整数 vi, ti，表示编号为 i 的结点值和下一结点编号。
 * ti = -1 表示下一指针为空。
 * 输入保证从两个头结点出发均不会进入环，并且同一结点只有唯一的下一结点。
 * 
 * 【输出格式】
 * 若两条链相交，输出第一个公共结点的编号；若不相交，输出 -1。
 * 
 * 【数据范围】
 * - 0 <= n <= 6 * 10^4
 * - -1 <= hA, hB < n
 * - 1 <= vi <= 10^5
 * - -1 <= ti < n
 * 
 * 【输入样例】
 * 8 0 2
 * 4 1
 * 1 5
 * 5 3
 * 6 4
 * 1 5
 * 8 6
 * 4 7
 * 5 -1
 * 
 * 【输出样例】
 * 5
 * 
 * 【样例说明】
 * 链 A (从 hA=0 出发)：0 -> 1 -> 5 -> 6 -> 7
 * 链 B (从 hB=2 出发)：2 -> 3 -> 4 -> 5 -> 6 -> 7
 * 两条链在编号为 5 的结点处首次相交，因此输出 5。
 */

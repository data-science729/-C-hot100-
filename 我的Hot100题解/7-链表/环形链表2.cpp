/**
 * 题目：142. 环形链表 II (Linked List Cycle II)
 * 难度：中等
 * 
 * 【题目描述】
 * 给定一个链表的头节点 head，返回链表开始入环的第一个节点。如果链表无环，则返回 null。
 * 如果链表中有某个节点，可以通过连续跟踪 next 指针再次到达，则链表中存在环。
 * 不允许修改链表。
 * 
 * 【输入描述 (ACM风格)】
 * 输入包含多组测试数据，处理到文件末尾 (EOF)。
 * 每组数据占两行：
 * 第一行包含两个整数 n 和 pos，分别表示链表节点数和尾节点连接的环入口索引（0-indexed）：
 *   - n (0 <= n <= 10^4)
 *   - pos: 若 pos 为 -1，表示链表无环；若 0 <= pos < n，表示尾节点指向第 pos 个节点。
 * 第二行包含 n 个整数，表示链表中各个节点的值 val (-10^5 <= val <= 10^5)。若 n = 0，则此行为空。
 * 
 * 【输出描述 (ACM风格)】
 * 对于每组测试数据：
 * - 若链表存在环，输出入环的第一个节点的索引值（即题目中的 pos）；
 * - 若链表无环（或 head 为空），输出 "null"。
 * 每组结果输出占一行。
 * 
 * 【输入样例】
 * 4 1
 * 3 2 0 -4
 * 2 0
 * 1 2
 * 1 -1
 * 1
 * 0 -1
 * 
 * 【输出样例】
 * 1
 * 0
 * null
 * null
 * 
 * 【数据范围与限制】
 * - 链表节点数 n: 0 <= n <= 10^4
 * - 节点值 Node.val: -10^5 <= Node.val <= 10^5
 * - pos 的值为 -1 或 [0, n - 1] 内的一个有效索引
 * - 进阶要求：时间复杂度 O(N)，空间复杂度 O(1)
 */
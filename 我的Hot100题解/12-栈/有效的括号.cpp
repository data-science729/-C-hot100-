/*
 * =====================================================================
 * LeetCode 20. 有效的括号 (Valid Parentheses)
 * 难度：简单
 * 
 * 题目描述：
 * 给定一个只包括 '('，')'，'{'，'}'，'['，']' 的字符串 s ，判断字符串是否有效。
 * 有效字符串需满足：
 * 1. 左括号必须用相同类型的右括号闭合。
 * 2. 左括号必须以正确的顺序闭合。
 * 3. 每个右括号都有一个对应的相同类型的左括号。
 * 
 * 示例 1：
 * 输入：s = "()"
 * 输出：true
 * 
 * 示例 2：
 * 输入：s = "()[]{}"
 * 输出：true
 * 
 * 示例 3：
 * 输入：s = "(]"
 * 输出：false
 * 
 * 示例 4：
 * 输入：s = "([])"
 * 输出：true
 * 
 * 示例 5：
 * 输入：s = "([)]"
 * 输出：false
 * 
 * 提示：
 * 1 <= s.length <= 10^4
 * s 仅由括号 '()[]{}' 组成
 * =====================================================================
 */
#include<bits/stdc++.h>
using namespace std;

bool solve(const string s)
{
   //1.创建一个字符栈
   stack<char> st;
   //2.遍历字符串中的每个字符
   //写法:一次取出字符串s中的每个字符并赋值给变量c
   //因此循环内部直接写c 不需要写c[i]
   for(char c: s)
   {
       //3.如果是左括号 入栈
       if(c == '(' || c == '[' || c == '{')
       {
        st.push(c);
       }
       //4.如果是右括号 检查栈是否为空 为空没法匹配直接false
       else
       {
       //5.栈为空时无法匹配
       if(st.empty())  return false;
       //6.检查栈顶是否与当前右括号匹配
       if(c == ')' && st.top() != '(') return false;
       if(c == ']' && st.top() != '[') return false;
       if(c == '}' && st.top() != '{') return false;
       //7.匹配成功弹出栈顶
       st.pop();
       }
   }
   //8.最终栈为空才表示匹配成功
   return st.empty();
}

int main()
{
   string s;
   while(cin>>s)
   {
    if(solve(s))
    {
        cout<<"true"<<'\n';
    }
    else
    {
        cout<<"false"<<'\n';
    }
   }
   return 0;
}
// 739. 每日温度
// 中等
//
// 相关标签
// 相关企业
//
// 提示
//
// 给定一个整数数组 temperatures ，表示每天的温度，返回一个数组 answer ，其中 answer[i] 是指对于第 i 天，下一个更高温度出现在几天后。如果气温在这之后都不会升高，请在该位置用 0 来代替。
//
// 示例 1:
//
// 输入: temperatures = [73,74,75,71,69,72,76,73]
// 输出: [1,1,4,2,1,1,0,0]
//
// 示例 2:
//
// 输入: temperatures = [30,40,50,60]
// 输出: [1,1,1,0]
//
// 示例 3:
//
// 输入: temperatures = [30,60,90]
// 输出: [1,1,0]
//
// 提示：
//
// 1 <= temperatures.length <= 10^5
// 30 <= temperatures[i] <= 100

//单调栈:在普通栈的基础上 保持栈内元素从栈底到栈顶始终保持单调递增或者单调递减
//单调递增栈:从栈底到栈顶 元素越来越大  -->通常用于找更小元素
//单调递减栈:从栈底到栈顶 元素越来越小  -->通常用于找更大元素

//单调递增栈入栈规则:当前元素x 如果栈不为空 且栈顶元素大于x 就弹出栈顶
//不是只检查一次 而是通过while持续弹出 直到恢复单调性:重复上述操作 直到栈为空 或者栈顶不大于x
//将x入栈

//价值:当新元素出现时 它可以帮助我们确定之前某些元素的答案

#include<bits/stdc++.h>
using namespace std;

//本题 找的是天数 因而栈中存下标 通过下标访问温度
vector<int> solve(vector<int>& tp)
{
    int n = tp.size();
    vector<int> answer(n,0);
    //单调递减栈 存储下标
    stack<int> st;
    for(int i = 0 ;i<n;i++)
    {
        //当前温度高于栈顶的温度 
        //说明当前日期是栈顶日期右侧第一个更高温度
        while(!st.empty() && tp[i] > tp[st.top()])
        {
            //取出尚未找到的更高温度的日期下标
            int prev = st.top();
            st.pop();
            answer[prev] = i - prev;
        }
        //当前日期还没有确定答案 入栈等待
        st.push(i);
    }
    return answer;
}

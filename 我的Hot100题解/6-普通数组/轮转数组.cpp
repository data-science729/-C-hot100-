/*
 * ==============================================================================
 * 189. 轮转数组
 * 难度：中等
 * 
 * 题目描述：
 * 给定一个整数数组 nums，将数组中的元素向右轮转 k 个位置，其中 k 是非负数。
 * 
 * 示例 1：
 * 输入: nums = [1,2,3,4,5,6,7], k = 3
 * 输出: [5,6,7,1,2,3,4]
 * 解释:
 * 向右轮转 1 步: [7,1,2,3,4,5,6]
 * 向右轮转 2 步: [6,7,1,2,3,4,5]
 * 向右轮转 3 步: [5,6,7,1,2,3,4]
 * 
 * 示例 2：
 * 输入：nums = [-1,-100,3,99], k = 2
 * 输出：[3,99,-1,-100]
 * 解释: 
 * 向右轮转 1 步: [99,-1,-100,3]
 * 向右轮转 2 步: [3,99,-1,-100]
 * 
 * 提示：
 * - 1 <= nums.length <= 10^5
 * - -2^31 <= nums[i] <= 2^31 - 1
 * - 0 <= k <= 10^5
 * 
 * 进阶：
 * - 尽可能想出更多的解决方案，至少有三种不同的方法可以解决这个问题。
 * - 你可以使用空间复杂度为 O(1) 的 原地 算法解决这个问题吗？
 * ==============================================================================
 */
#include<bits/stdc++.h>
using namespace std;


vector<int> solve(vector<int>& nums,int k)
{
     int n = nums.size();
     //对k取模 消除完整轮转的圈数 例如n=7,k=10,实际只需要右移三位
     k%=n;
     //创造长度为n的辅助数组 用来存放每个元素轮转后的结果
     vector<int> temp(n);
     //遍历数组 将每个元素放到新位置
     for(int i = 0;i<n;i++)
     {
        int j = (i+k)%n;
        //将原数组下标i的元素放到新下标j
        temp[j] = nums[i];
     }
    return temp;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int n,k;
    while(cin>>n>>k)
    {
        vector<int> nums(n);
        for(int i = 0 ;i<n;i++)
        {
            cin>>nums[i];
        }
        vector<int> ans = solve(nums,k);
        //输出结果 元素之间用空格分隔
        for(int i = 0 ;i<n;i++)
        {
            cout<<ans[i]<<(i==n-1?'\n':' ');
        }
    }
    return 0;
}


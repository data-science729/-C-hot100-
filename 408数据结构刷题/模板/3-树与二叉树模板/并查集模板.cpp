#include<bits/stdc++.h>
using namespace std;

/*
 * ============================================================
 *                    并查集（Disjoint Set Union）
 * ============================================================
 *
 * 【基本思想】
 *   用森林表示若干个互不相交的集合。
 *   每棵树代表一个集合，根结点作为该集合的代表元。
 *
 * 【核心操作】
 *   1. init(n)       : 初始化 n 个独立集合
 *   2. find(x)       : 查找 x 所在集合的根结点
 *   3. merge(x, y)   : 合并 x、y 所在的集合
 *   4. same(x, y)    : 判断 x、y 是否属于同一个集合
 *
 * 【优化方式】
 *   1. 路径压缩：Find 时将沿途结点直接连接到根结点
 *   2. 按秩合并：让秩较小的树挂到秩较大的树下面
 *   3. 按大小合并：让结点数量较少的集合挂到较大的集合下面
 *
 * 【复杂度】
 *   路径压缩 + 按秩合并：
 *   单次操作均摊 O(α(N))，α 为反阿克曼函数的反函数
 *
 *   空间复杂度：O(N)
 * ============================================================
 */
const int N = 2e5 + 5;

int parent[N]; //parent[i]:结点i的父结点


int rank_[N]; //rank_[i]:以i为根的树的秩，秩含义是"树高度的上界"

int sz[N]; //存以i为根的集合的元素个数

/*
 * ------------------------------------------------------------
 * 1. 初始化 init(n)
 * ------------------------------------------------------------
 *
 * 初始时，每个元素各自构成一个独立集合。
 *
 * parent[i] = i：每个元素的父结点是自己，即自身为根
 * rank_[i] = 1：初始化秩为 1
 * sz[i] = 1：每个集合只有一个元素
 *
 * 时间复杂度：O(N)
 */
void init(int n)
{
    for(int i = 1;i<=n;i++)  //遍历从1到n元素
    {
        parent[i] = i;
        rank_[i] = 1;   //每棵树初始只有1层，秩为1
        sz[i] = 1;   //每个集合初始只有1个元素 大小为1
    }
}

/*
 * ------------------------------------------------------------
 * 2. 查找 find(x) —— 路径压缩
 * ------------------------------------------------------------
 *
 * 功能：返回 x 所在集合的根结点（代表元）。
 *
 * 根结点的判断条件：
 *     parent[x] == x
 *
 * 路径压缩：
 *     parent[x] = find(parent[x]);
 *
 * 将当前结点直接连接到递归找到的根结点，
 * 从而压缩查找路径，降低后续操作的开销。
 *
 * 时间复杂度：与按秩合并配合时，均摊 O(α(N))
 */
int find(int x)
{
    if(parent[x] == x)  return x; //递归出口 找到根
    int root = find(parent[x]); // 递:先一路往上找到真正的根结点
    parent[x] = root; // 归:回溯时，把当前结点直接挂到根下
    return root; //返回根结点
}

/*
 * ------------------------------------------------------------
 * 3. 合并 merge(x, y) —— 按秩合并
 * ------------------------------------------------------------
 *
 * 功能：合并 x、y 所在的两个集合。
 *
 * 步骤：
 *   1. 分别找到 x、y 所在集合的根结点
 *   2. 如果根结点相同，说明已经属于同一集合
 *   3. 否则，让秩较小的树挂到秩较大的树下面
 *   4. 如果两棵树的秩相同，合并后新根的秩加 1
 *
 * 注意：
 *   必须合并两个根结点，而不是直接合并 x 和 y。
 *
 * 时间复杂度：与路径压缩配合时，均摊 O(α(N))
 */
void merge(int x,int y)
{
    int rx = find(x);  //找x所在树的根
    int ry = find(y); //找y所在树的根
    //已经属于同一集合 无须重复合并
    if(rx == ry)  return;
    //rx这棵树更矮
    if(rank_[rx] < rank_[ry])
    {
        parent[rx] = ry; //矮树挂到高树ry下面，ry依然是根
    }
    else if(rank_[rx] > rank_[ry])
    {
        parent[ry] = rx;
    }
    //两棵树秩相同，任选一个作为新根，秩增加1
    else
    {
        parent[ry] = rx; //这里选rx档新根 ry挂到rx下面
        rank_[rx]++;  //等高合并后 新树整体深度会多出一层 所以新根秩+1
    }
}

/*
 * ------------------------------------------------------------
 * 4. 查询 same(x, y)
 * ------------------------------------------------------------
 *
 * 功能：判断 x、y 是否属于同一个集合。
 *
 * 原理：
 *   如果两个元素的根结点相同，
 *   则它们属于同一个集合。
 *
 * 返回值：
 *   true  ：属于同一个集合
 *   false ：不属于同一个集合
 *
 * 时间复杂度：均摊 O(α(N))
 */
bool same(int x,int y)
{
    return find(x) == find(y);
}

/*
 * ============================================================
 *             以下为两种可选的合并方式
 * ============================================================
 *
 * 注意：
 *   以下函数与上面的 merge() 不能同时使用同一个函数名。
 *   使用时，选择其中一种替换原来的 merge() 即可。
 */


/*
 * ------------------------------------------------------------
 * 5. 普通合并 merge_basic(x, y)
 * ------------------------------------------------------------
 *
 * 不考虑树的秩或集合大小，直接让一个根指向另一个根。
 *
 * 优点：实现简单
 * 缺点：可能导致树退化成链表
 *
 * 配合路径压缩仍可改善实际效率，但没有按秩合并的
 * O(α(N)) 均摊复杂度保证。
 */
void merge_basic(int x,int y)
{
    int rx = find(x);
    int ry = find(y);
    if(rx != ry)  //不在同一集合中 
    {
        parent[rx] = ry;  //啥都不看 直接就把rx挂到ry下面 任由高度增长
    }
}


/*
 * ------------------------------------------------------------
 * 6. 按大小合并 merge_size(x, y)
 * ------------------------------------------------------------
 *
 * 让元素数量较少的集合挂到元素数量较多的集合下面。
 *
 * sz[根]：表示该根结点所在集合的元素数量。
 *
 * 合并后：
 *   sz[新根] = sz[新根] + sz[旧根]
 *
 * 注意：
 *   只有根结点的 sz 值有意义。
 */
void merge_size(int x,int y)
{
    int rx = find(x);
    int ry = find(y);

    if(rx == ry)  return;
    //保证rx是较大集合的根
    if(sz[rx]<sz[ry])  swap(rx,ry);
    //较小集合挂在较大集合下面
    parent[ry] = rx; 
    //更新新根所代表的集合的大小
    sz[rx] += sz[ry];
}

/**
 * ==============================================================================
 * 题目：表达式求值（Expression Evaluation）
 * ==============================================================================
 *
 * 题目描述：
 * 给定一个合法的中缀算术表达式 s，请利用栈完成以下三个任务：
 *
 * 1. 将中缀表达式转换为后缀表达式（逆波兰表达式）。
 * 2. 利用后缀表达式计算表达式的值。
 * 3. 直接利用两个栈对原中缀表达式求值。
 *
 * 要求两种求值方式的结果一致。
 *
 * ------------------------------------------------------------------------------
 * 表达式规则：
 *
 * 1. 支持以下运算符：
 *    +  加法，优先级为 1
 *    -  减法，优先级为 1
 *    *  乘法，优先级为 2
 *    /  除法，优先级为 2
 *    ( ) 括号
 *
 * 2. 同级运算符按照左结合处理。
 * 3. 操作数均为整数，允许多位数。
 * 4. 表达式中允许出现空格。
 * 5. 括号保证合法且匹配。
 * 6. 不考虑一元正负号，负数需要通过减法表达。
 * 7. 不存在除零运算。
 * 8. 除法采用向零截断。
 * 9. 所有中间结果和最终结果均可用 32 位有符号整数表示。
 *
 * ------------------------------------------------------------------------------
 * 输入格式：
 *
 * 多组测试数据，每组输入一行，包含一个合法的中缀表达式。
 * 输入以 EOF 结束。
 *
 * ------------------------------------------------------------------------------
 * 输出格式：
 *
 * 对于每组测试数据，输出三行：
 *
 * 第一行：转换得到的后缀表达式。
 * 第二行：利用后缀表达式计算得到的结果。
 * 第三行：利用双栈法直接计算中缀表达式得到的结果。
 *
 * ------------------------------------------------------------------------------
 * 输入样例：
 *
 * (2 + 1) * 3
 * 4 + 13 / 5
 * 10 * (6 + 9 - 3) / 2 + 17 + 5
 * 8 - 3 - 2
 *
 * ------------------------------------------------------------------------------
 * 输出样例：
 *
 * 2 1 + 3 *
 * 9
 * 9
 * 4 13 5 / +
 * 6
 * 6
 * 10 6 9 + 3 - * 2 / 17 + 5 +
 * 77
 * 77
 * 8 3 - 2 -
 * 3
 * 3
 *
 * ------------------------------------------------------------------------------
 * 算法要求：
 *
 * 1. 必须使用 C++ STL 中的 stack 容器。
 * 2. 中缀转后缀表达式必须使用运算符栈。
 * 3. 后缀表达式求值必须使用操作数栈。
 * 4. 中缀表达式直接求值必须使用两个栈：
 *    - 操作数栈：存储参与运算的数字。
 *    - 运算符栈：存储运算符及括号。
 * 5. 将三个过程分别封装为独立函数。
 * 6. 采用 ACM 输入输出格式，支持 EOF 多组测试数据。
 *
 * ------------------------------------------------------------------------------
 * 核心考点：
 *
 * 1. 中缀表达式转后缀表达式。
 * 2. 后缀表达式求值。
 * 3. 中缀表达式直接求值（双栈法）。
 * 4. 运算符优先级与结合性。
 * 5. 栈的 push()、top()、pop() 操作。
 *
 * ==============================================================================
 */
#include<bits/stdc++.h>
using namespace std;

//优先级函数(只处理二元四则运算)
int priority(char op)
{
  if(op =='+' || op == '-') return 1;
  if(op == '*'|| op == '/') return 2;
  return 0;
}
//1.中缀表达式转后缀表达式
string infixToPostfix(const string& s)
{
    //运算符栈
     stack<char> st;
     //保存最终转换结果
     string ans;

     //使用下标i扫描中缀表达式
     //不能简单i++ 因为读取多位整数时需要连续移动下标
     for(int i = 0 ;i<s.size();)
     {
       //1.遇到空格:跳过
       if(s[i] == ' ')  i++;
       //2.遇到数字:bool isdigit(char) 检查一个字符是否为十进制数字
       else if(isdigit(s[i]))
       {
        //连续读取完整的整数
        while(i<s.size() && isdigit(s[i]))
        {
            ans += s[i];
            i++;
        }
        //每个操作数后添加空格 以区分不同的token
        ans += ' ';
       }
       //3.遇到左括号:直接入栈
       else if(s[i] == '(')
       {
        st.push(s[i]);
        i++;
       }
       //4.遇到右括号:不断弹出运算符并输出直到遇到左括号
       else if(s[i] == ')')
       {
        while(!st.empty() && st.top() != '(')
        {
            //将栈顶运算符加入后缀表达式
            ans += st.top();
            ans += ' ';
            st.pop();
        }
        //弹出左括号本身 但不输出
        st.pop();
        i++;
       }
       //5.遇到运算符
       else
       {
        //和栈顶运算符比较优先级
        while(!st.empty() &&
              st.top() != '(' &&
              priority(st.top()) >= priority(s[i]))
              {
                //栈顶运算符优先级更高 先输出他
                ans += st.top();
                ans += ' ';
                st.pop();
              }
              //当前运算符暂时不能输出 入栈等待后续处理
              st.push(s[i]);
              i++;
    
       }
       //6.中缀表达式扫描结束 将栈中剩余运算符弹出
       while(!st.empty())
       {
        ans += st.top();
        ans += ' ';
        st.pop();
       }
    }
    if(!ans.empty())
    {
        ans.pop_back();
    }
    return ans;
}


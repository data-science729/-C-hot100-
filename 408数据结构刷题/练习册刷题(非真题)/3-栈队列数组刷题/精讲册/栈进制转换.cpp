/**
 * ==============================================================================
 * 题目：十进制数的任意进制转换（Radix Conversion）
 * ==============================================================================
 * 题目描述：
 * 给定一个非负十进制整数 n 和一个目标进制 b，请利用栈（Stack）将十进制整数
 * n 转换为 b 进制数，并输出转换结果。
 * 
 * 转换规则如下：
 * 1. 不断将当前整数除以目标进制 b，记录每次除法得到的余数。
 * 2. 将每次得到的余数依次压入栈中。
 * 3. 当商为 0 时，停止除法。
 * 4. 依次弹出栈中的元素，按照弹出顺序输出，即得到目标进制表示。
 * 
 * 特别说明：
 * - 当目标进制 b 不超过 10 时，直接使用数字 0～9 表示各位。
 * - 当目标进制 b 大于 10 时，使用大写字母 A～Z 表示数值 10～35。
 *   例如，十进制数 15 转换为十六进制数，结果为 F。
 * - 当 n = 0 时，输出 0。
 * 
 * 输入格式：
 * 每组输入包含两个整数 n 和 b，分别表示待转换的十进制整数和目标进制。
 * 输入包含多组测试数据，以 EOF 结束。
 * 
 * 输出格式：
 * 对于每组测试数据，输出一行转换后的目标进制数。
 * 
 * 数据范围：
 * 0 <= n <= 10^18
 * 2 <= b <= 36
 * 
 * 输入样例：
 * 42 2
 * 156 8
 * 255 16
 * 12345 36
 * 0 2
 * 
 * 输出样例：
 * 101010
 * 234
 * FF
 * 9IX
 * 0
 * 
 * 算法要求：
 * - 必须使用 C++ STL 中的 stack 容器完成进制转换，不允许直接调用库函数
 *   实现进制转换。
 * - 建议将转换过程封装为独立函数。
 * ==============================================================================
 */
#include<bits/stdc++.h>
using namespace std;

//将0-35的数值映射为对应的进制字符
char digit(int x)
{
    if(x<10)  return '0' + x;
    return 'A' + (x-10);
}

//十进制转b进制
string solve(long long n,int b)
{
    stack<char> st;
    //特判:0转换成任何进制都是0
    if(n == 0)  return "0";
    //除基取余法
    while(n>0)
    {
        int r = n % b;  //获取当前余数
        st.push(digit(r)); //将余数对应的字符入栈
        n = n / b; //更新当前的整数为商
    }
    //依次弹出栈顶元素 得到正确的输出顺序
    string ans;
    while(!st.empty())
    {
        ans += st.top(); //获取栈顶元素
        st.pop(); //弹出栈顶元素
    }
    return ans;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    long long n;
    int b;
    while(cin>>n>>b)
    {
        cout<<solve(n,b)<<'\n';
    }
    return 0;
}


/**
 * ============================================================================
 * 【题目名称】翻转二叉树
 * ============================================================================
 *
 * 【题目描述】
 *   给定一棵二叉树，将每个结点的左、右子树交换，输出翻转后的二叉树。
 *
 * 【输入格式】
 *   第一行：整数 n，表示随后层序序列中的记号数。
 *   第二行：n 个以空格分隔的记号，按层序表示二叉树。整数表示结点值，null
 *          表示空孩子（仅保留到最后一个非空结点为止；若根结点为空，则输入一个 null）。
 *
 * 【输出格式】
 *   按相同的层序格式输出翻转后的二叉树，并删除末尾多余的 null。空树输出 null。
 *
 * 【数据范围】
 *   1 <= n <= 201，非空结点数不超过 100，-100 <= 结点值 <= 100
 *
 * 【样例】
 *   输入：
 *     7
 *     4 2 7 1 3 6 9
 *   输出：
 *     4 7 2 9 6 3 1
 * ============================================================================
 */
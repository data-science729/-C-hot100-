/*
 * ============================================================================
 * 题目名称：由中根序列和后根序列重建二叉树（中后序求前序）
 * 题目来源：数据结构与算法 A 编程作业 · 第五章二叉树 A 题（经典 OJ 原题）
 * ----------------------------------------------------------------------------
 * 【题目描述】
 *   我们知道如何按照三种深度优先次序来周游一棵二叉树，来得到中根序列、前根序列
 *   和后根序列。反过来，如果给定二叉树的中根序列和后根序列，或者给定中根序列和
 *   前根序列，可以重建一棵二叉树。
 *   本题输入一棵二叉树的中根序列和后根序列，要求在内存中重建二叉树，最后输出这
 *   棵二叉树的前根序列。
 *   用不同的整数来唯一标识二叉树的每一个结点。例如：
 *     中根序列：9 5 32 67
 *     后根序列：9 32 67 5
 *     前根序列：5 9 67 32
 *
 * 【输入格式】
 *   两行。第一行是二叉树的中根序列，第二行是后根序列。
 *   每个数字表示的结点之间用空格隔开。
 *   结点数字范围：0 ~ 65535（各不相同）。暂不必考虑不合理的输入数据。
 *
 * 【输出格式】
 *   一行。由输入中的中根序列和后根序列重建的二叉树的前根序列，数字间用空格隔开。
 *
 * 【样例输入】
 *   9 5 32 67
 *   9 32 67 5
 *
 * 【样例输出】
 *   5 9 67 32
 * ============================================================================
 */